/** Run on demand with a local server and Chrome. All mutations use actual UI. */
import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
const out='/tmp/token-arcade-cozy-v2'; mkdirSync(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true,ignoreDefaultArgs:['--headless=old'],args:['--headless=new']});
const p=await browser.newPage({viewport:{width:1600,height:1000},deviceScaleFactor:1});
const errors=[],api=[],checks=[];
p.on('pageerror',e=>errors.push(e.message));
p.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
p.on('request',r=>{if(r.url().includes('/api/'))api.push(r.url());});
const state=()=>p.evaluate(()=>window.cozyPreview.snapshot());
const stable=()=>p.waitForSelector('#preview-boot',{state:'detached'});
const close=async()=>{await p.keyboard.press('Escape');await p.waitForTimeout(80);};
const shot=async name=>{await p.mouse.move(1590,990);await p.screenshot({path:`${out}/${name}.png`});};
try {
 await p.goto('http://localhost:4173/cozy.html');await stable();
 const originalLocal=await p.evaluate(()=>JSON.stringify(localStorage));
 const start=await state();assert.equal(start.coins,9);
 await shot('01-room');
 await p.mouse.click(920,480);
 await p.waitForFunction(()=>window.cozyPreview.snapshot().coins===25);
 assert.ok((await state()).player.y<start.player.y-60);checks.push('Clicking bank walks to it and mints 16 coins');
 await p.keyboard.press('j');await p.waitForTimeout(80);
 const frozen=(await state()).player;await p.keyboard.down('ArrowRight');await p.waitForTimeout(200);await p.keyboard.up('ArrowRight');assert.deepEqual((await state()).player,frozen);
 await p.mouse.click(1040,617);await p.waitForTimeout(80);assert.equal((await state()).placing,'c_sprout');
 await p.mouse.click(405,780);await p.waitForTimeout(80);assert.equal((await state()).progress.slots[3],'c_sprout');
 await p.reload();await stable();assert.equal((await state()).progress.slots[3],'c_sprout');checks.push('Modal input isolation and chosen placement survive reload');
 await p.keyboard.press('g');await p.waitForTimeout(80);await p.mouse.click(455,825);await p.waitForTimeout(80);
 assert.equal((await state()).coins,0);assert.equal((await state()).progress.pending.length,1);
 await p.mouse.click(455,825);await p.waitForTimeout(80);assert.equal((await state()).progress.pending.length,1);
 await p.reload();await stable();assert.equal((await state()).coins,0);assert.equal((await state()).progress.pending.length,1);
 checks.push('Pending reveal prevents double spending and survives reload');
 await p.mouse.click(1150,851);await p.waitForTimeout(80);assert.equal((await state()).progress.pending.length,0);
 await p.mouse.click(800,900);await p.waitForFunction(()=>window.cozyPreview.snapshot().coins===25);checks.push('Insufficient coins lead back to a real collection interaction');
 await p.keyboard.press('g');await p.waitForTimeout(80);await p.mouse.click(455,825);await p.waitForTimeout(80);
 await p.mouse.click(1040,475);await p.waitForTimeout(80);await p.mouse.click(1150,851);await p.waitForTimeout(80);assert.equal((await state()).coins,0);checks.push('A second pull works and its capsule can be opened by clicking');
 await close();
 for(let i=0;i<3;i++){await p.waitForTimeout(1850);await p.keyboard.press('r');await p.waitForTimeout(80);}
 assert.equal((await state()).coins,250);
 await p.keyboard.press('g');await p.waitForTimeout(80);await p.mouse.click(800,825);await p.waitForTimeout(80);
 assert.equal((await state()).coins,25);assert.equal((await state()).progress.pending.length,10);
 await p.mouse.click(1040,475);await p.waitForTimeout(80);await shot('02-ten-results');await p.mouse.click(1150,851);await p.waitForTimeout(80);checks.push('Ten pulls cost 225 and every reward is retained');
 await close();await p.keyboard.press('c');await p.waitForTimeout(80);await shot('03-collection');
 await p.mouse.click(1158,804);await p.waitForTimeout(80);assert.ok(await p.locator('[data-action="collection-u_star"]').count());checks.push('Collection book can browse the full catalog');
 await close();await p.keyboard.press('Tab');await p.keyboard.press('Enter');await p.waitForTimeout(80);assert.equal((await state()).dialog,'menu');checks.push('Keyboard focus opens the room menu');
 await p.mouse.click(800,550);await p.waitForTimeout(80);assert.equal((await state()).locale,'en');
 await close();await shot('04-room-after');
 assert.equal(await p.evaluate(()=>JSON.stringify(localStorage)),originalLocal);assert.deepEqual(api,[]);assert.deepEqual(errors,[]);checks.push('Production local storage untouched, no usage API calls or browser errors');
 writeFileSync(`${out}/checks.json`,JSON.stringify(checks,null,2));console.log(checks.join('\n'));
} finally {await browser.close();}
